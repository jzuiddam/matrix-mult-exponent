#!/usr/bin/python3
"""Emit the Round-61 released-count cohorts.

Default: one shared base module and 24 cohorts, four
per region r = 0..5 over the parent intervals 000-031, 032-063, 064-095 and
096-125.  Every cohort keeps each compatibility definition
`coefficientQP<p>R<r>` byte-identical to the retired per-parent leaf (consumers
close `... = coefficientQP<p>R<r>` by `rfl`), certifies all its rows with one
`native_decide`, and recovers every `coefficientP<p>R<r>_eq_released` with its
exact leaf type as a kernel projection.  `--pilot` reproduces an earlier, superseded
bounded region-0 P000--P015 variant (not part of this release) byte for byte.

Both modes reuse the released-certificate extraction and the Round-61 parent
construction instead of parsing generated Lean leaves.  Inputs and the reused
emitters are pinned before any extraction runs.  `--leaves DIR` additionally
requires every emitted coefficient definition to equal, byte for byte, the
definition line of the corresponding leaf in DIR (run before leaf deletion).
"""

from __future__ import annotations

import argparse
import hashlib
import os
from pathlib import Path
import sys


HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
TOOLS = REPO / "tools"
OUT = REPO / "OmegaBound"
_MAT_REL = "experiments/more_asymmetry_reference/upstream/data/W1.00_2.371339.mat"
# $MATMUL_UPSTREAM_DIR is a directory holding the authors' upstream data file
# (at _MAT_REL) and a Sage verifier (the package
# experiments.more_asymmetry_sage_verifier).  Neither is shipped; the data file
# is accepted only by its pin.
UPSTREAM = Path(os.environ.get("MATMUL_UPSTREAM_DIR", "")).expanduser()
MAT = UPSTREAM / _MAT_REL

REGION = 0
START = 0
COUNT = 16
CHECK_MODULE = "ReleaseCompactR61CohortR0P000P015Check"
AXIOMS_MODULE = "ReleaseCompactR61CohortR0P000P015Axioms"

PINS = {
    MAT: "783353fda82acb3fb93c247dcad857b2db5f61944f5d0e91ae5f9e5a6c7feec3",
    TOOLS / "advxxz_t6_round60.py":
        "3d48fae83d03089725f90b86e93ad6e32cb42284a6eca169eda837b8ec582706",
    TOOLS / "advxxz_retained_cert.py":
        "1a1083eec38e302cc47800dc951c21148b9c9f7c7edc45216035594fcf4c43da",
    TOOLS / "advxxz_cert.py":
        "3e5f2695088eb5025ebadaaa3a9c3896506390318b711e4cc965f7831fea84e1",
}


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def verify_pins() -> None:
    if not os.environ.get("MATMUL_UPSTREAM_DIR"):
        raise SystemExit("set MATMUL_UPSTREAM_DIR to the directory holding the authors' upstream "
                         f"data file ({_MAT_REL}) and a Sage verifier")
    for path, expected in PINS.items():
        if not path.is_file():
            raise SystemExit(f"missing pinned input: {path}")
        observed = sha256(path)
        if observed != expected:
            raise SystemExit(
                f"pin mismatch for {path}: observed {observed}, expected {expected}")


def conjunction_projection(index: int) -> str:
    if not 0 <= index < COUNT:
        raise ValueError(index)
    if index == COUNT - 1:
        return ".2" * index
    return ".2" * index + ".1"


def level3_terms():
    verify_pins()
    sys.path.insert(0, str(TOOLS))
    sys.path.insert(0, str(UPSTREAM))
    import advxxz_cert  # noqa: PLC0415
    import advxxz_retained_cert  # noqa: PLC0415
    # The reused extractor names the same pinned file through an absolute path of
    # its original machine.  Point both imported module globals at the copy
    # verified above; do not reimplement extraction.
    advxxz_cert.MAT = MAT
    advxxz_retained_cert.MAT = MAT
    from advxxz_retained_cert import formulas  # noqa: PLC0415
    from advxxz_t6_round60 import make_parent, rat_q  # noqa: PLC0415
    from experiments.more_asymmetry_sage_verifier.verifier import (  # noqa: PLC0415
        GeneralTerm,
    )

    _expressions, _semantic, verifier, _repaired = formulas()
    terms = [term for term in verifier.registry.by_level[3]
             if isinstance(term, GeneralTerm)]
    if len(terms) != 126:
        raise ArithmeticError(f"expected 126 level-3 parents, found {len(terms)}")
    return terms, make_parent, rat_q


def pilot_sources():
    terms, make_parent, rat_q = level3_terms()
    certificates = {}
    parents = [make_parent(terms[p], REGION, certificates)
               for p in range(START, START + COUNT)]

    lines = [
        "-- GENERATED by release/emitters/emit_round61_cohorts.py.\n",
        "-- Pinned cohort: released region 0, consecutive parents P000--P015.\n",
        "import OmegaBound.ADVXXZT6Round61ReleasedCountProbe\n\n",
        "set_option maxRecDepth 100000\n",
        "set_option linter.style.longLine false\n\n",
        "open Finset\n\n",
        "namespace OmegaBound.ADVXXZT6Round61\n\n",
        "/-- The sixteen released coefficient rows, stored once for the cohort. -/\n",
        "def releaseCompactR61CoefficientsR0P000P015 : Fin 16 → ℚ := ![\n    ",
        ",\n    ".join(rat_q(parent.coefficient) for parent in parents),
        "\n  ]\n\n",
    ]
    for offset, _parent in enumerate(parents):
        parent = START + offset
        lines += [
            f"def coefficientQP{parent:03d}R0 : ℚ := "
            f"releaseCompactR61CoefficientsR0P000P015 {offset}\n\n",
        ]

    lines += [
        "/-- The closed integer/rational predicate checked for every cohort row. -/\n",
        "def releaseCompactR61RowOK (p : Fin 126) (coefficient : ℚ) : Prop :=\n",
        "  coefficient =\n",
        "    (∑ d : Fin (ADVXXZT2.parKids p.1).length,\n",
        "      ADVXXZT6Selection.firstMultiplicity 0 1 p d) /\n",
        "        ((ADVXXZT2.certDen : ℚ) ^ 4)\n\n",
        "theorem releaseCompactR61Coefficient_eq_of_rowOK\n",
        "    (p : Fin 126) (coefficient : ℚ)\n",
        "    (h : releaseCompactR61RowOK p coefficient) :\n",
        "    releasedParentCoefficient 0 p = (coefficient : Real) := by\n",
        "  apply releasedParentCoefficient_eq_rat coefficient\n",
        "  rw [releasedParentPart_card_eq_sum_firstMultiplicity]\n",
        "  exact h\n",
        "\n",
        "/-- One executable certificate for all sixteen rows. -/\n",
        "theorem releaseCompactR61CohortR0P000P015Check :\n    ",
        " ∧\n    ".join(
            f"releaseCompactR61RowOK {parent} "
            f"(releaseCompactR61CoefficientsR0P000P015 {offset})"
            for offset, parent in enumerate(range(START, START + COUNT))),
        " := by\n",
        "  unfold releaseCompactR61RowOK\n",
        "  native_decide\n",
        "\n",
    ]

    for offset, _parent in enumerate(parents):
        parent = START + offset
        projection = conjunction_projection(offset)
        lines += [
            f"theorem coefficientP{parent:03d}R0_eq_released :\n",
            f"    releasedParentCoefficient 0 {parent} = "
            f"(coefficientQP{parent:03d}R0 : Real) :=\n",
            "  releaseCompactR61Coefficient_eq_of_rowOK "
            f"{parent} coefficientQP{parent:03d}R0\n",
            f"    releaseCompactR61CohortR0P000P015Check{projection}\n\n",
        ]
    lines.append("end OmegaBound.ADVXXZT6Round61\n")

    axioms = [
        "-- GENERATED by release/emitters/emit_round61_cohorts.py.\n",
        f"import OmegaBound.{CHECK_MODULE}\n\n",
        "#print axioms "
        "OmegaBound.ADVXXZT6Round61.releaseCompactR61CohortR0P000P015Check\n",
    ]
    axioms += [
        f"#print axioms OmegaBound.ADVXXZT6Round61."
        f"coefficientP{parent:03d}R0_eq_released\n"
        for parent in range(START, START + COUNT)
    ]
    return {
        OUT / f"{CHECK_MODULE}.lean": "".join(lines),
        OUT / f"{AXIOMS_MODULE}.lean": "".join(axioms),
    }


# --- production cohorts (COMPACT-T2) ----------------------------------------

REGIONS = range(6)
INTERVALS = ((0, 31), (32, 63), (64, 95), (96, 125))
BASE_MODULE = "ReleaseCompactR61CohortBase"


def cohort_module(region: int, lo: int, hi: int) -> str:
    return f"ReleaseCompactR61CohortR{region}P{lo:03d}P{hi:03d}Check"


def cohort_of(region: int, parent: int) -> str:
    """The production cohort carrying the released count row (region, parent)."""
    lo = 32 * (parent // 32)
    return cohort_module(region, lo, min(lo + 31, 125))


def projection(index: int, count: int) -> str:
    if not 0 <= index < count:
        raise ValueError(index)
    if index == count - 1:
        return ".2" * index
    return ".2" * index + ".1"


def coefficient_def(region: int, parent: int, literal: str) -> str:
    """Exactly the definition line of the retired per-parent leaf."""
    return f"def coefficientQP{parent:03d}R{region} : ℚ := {literal}\n"


def base_source() -> str:
    return "".join([
        "-- GENERATED by release/emitters/emit_round61_cohorts.py.\n",
        "-- Shared row predicate of the 24 production Round-61 count cohorts.\n",
        "import OmegaBound.ADVXXZT6Round61ReleasedCountProbe\n\n",
        "set_option linter.style.longLine false\n\n",
        "open Finset\n\n",
        "namespace OmegaBound.ADVXXZT6Round61\n\n",
        "/-- The closed integer/rational predicate checked for every cohort row. -/\n",
        "def releaseCompactR61RowOK (r : Fin 6) (p : Fin 126) (coefficient : ℚ) : Prop :=\n",
        "  coefficient =\n",
        "    (∑ d : Fin (ADVXXZT2.parKids p.1).length,\n",
        "      ADVXXZT6Selection.firstMultiplicity r 1 p d) /\n",
        "        ((ADVXXZT2.certDen : ℚ) ^ 4)\n\n",
        "theorem releaseCompactR61Coefficient_eq_of_rowOK\n",
        "    (r : Fin 6) (p : Fin 126) (coefficient : ℚ)\n",
        "    (h : releaseCompactR61RowOK r p coefficient) :\n",
        "    releasedParentCoefficient r p = (coefficient : Real) := by\n",
        "  apply releasedParentCoefficient_eq_rat coefficient\n",
        "  rw [releasedParentPart_card_eq_sum_firstMultiplicity]\n",
        "  exact h\n\n",
        "end OmegaBound.ADVXXZT6Round61\n",
    ])


def cohort_source(region: int, lo: int, hi: int, literals: dict) -> str:
    module = cohort_module(region, lo, hi)
    name = module[0].lower() + module[1:]
    parents = list(range(lo, hi + 1))
    count = len(parents)
    lines = [
        "-- GENERATED by release/emitters/emit_round61_cohorts.py.\n",
        f"-- Production cohort: released region {region}, parents "
        f"P{lo:03d}--P{hi:03d} ({count} rows, one native check).\n",
        f"import OmegaBound.{BASE_MODULE}\n\n",
        "set_option maxRecDepth 100000\n",
        "set_option linter.style.longLine false\n\n",
        "namespace OmegaBound.ADVXXZT6Round61\n\n",
    ]
    lines += [coefficient_def(region, p, literals[region, p]) + "\n" for p in parents]
    lines += [
        f"/-- One executable certificate for the {count} rows of this cohort. -/\n",
        f"theorem {name} :\n    ",
        " ∧\n    ".join(f"releaseCompactR61RowOK {region} {p} coefficientQP{p:03d}R{region}"
                        for p in parents),
        " := by\n",
        "  unfold releaseCompactR61RowOK\n",
        "  native_decide\n\n",
    ]
    for offset, p in enumerate(parents):
        lines += [
            f"theorem coefficientP{p:03d}R{region}_eq_released : "
            f"releasedParentCoefficient {region} {p} = (coefficientQP{p:03d}R{region} : Real) :=\n",
            f"  releaseCompactR61Coefficient_eq_of_rowOK {region} {p} coefficientQP{p:03d}R{region}\n",
            f"    {name}{projection(offset, count)}\n\n",
        ]
    lines.append("end OmegaBound.ADVXXZT6Round61\n")
    return "".join(lines)


def axioms_source() -> str:
    lines = ["-- GENERATED by release/emitters/emit_round61_cohorts.py (audit only, not release data).\n"]
    lines += [f"import OmegaBound.{cohort_module(r, lo, hi)}\n"
              for r in REGIONS for lo, hi in INTERVALS]
    lines.append("\n")
    for r in REGIONS:
        for lo, hi in INTERVALS:
            check = cohort_module(r, lo, hi)
            lines.append(f"#print axioms OmegaBound.ADVXXZT6Round61.{check[0].lower()}{check[1:]}\n")
            lines += [f"#print axioms OmegaBound.ADVXXZT6Round61.coefficientP{p:03d}R{r}_eq_released\n"
                      for p in range(lo, hi + 1)]
    return "".join(lines)


def production_sources(out: Path, with_axioms: bool):
    terms, make_parent, rat_q = level3_terms()
    literals = {}
    for r in REGIONS:
        certificates = {}
        for p in range(126):
            literals[r, p] = rat_q(make_parent(terms[p], r, certificates).coefficient)
    sources = {out / f"{BASE_MODULE}.lean": base_source()}
    for r in REGIONS:
        for lo, hi in INTERVALS:
            sources[out / f"{cohort_module(r, lo, hi)}.lean"] = cohort_source(r, lo, hi, literals)
    if with_axioms:
        sources[out / "ReleaseCompactR61CohortsAxioms.lean"] = axioms_source()
    return sources, literals


def leaf_mismatches(leaves: Path, literals: dict) -> list:
    bad = []
    for (r, p), literal in sorted(literals.items()):
        hits = sorted(leaves.glob(f"ADVXXZT6Round61ParentBlock*R{r}ReleasedCountP{p:03d}.lean"))
        if len(hits) != 1:
            bad.append(f"R{r} P{p:03d}: {len(hits)} leaf files")
            continue
        want = coefficient_def(r, p, literal)
        if want not in hits[0].read_text().splitlines(keepends=True):
            bad.append(f"R{r} P{p:03d}: definition differs from {hits[0].name}")
    return bad


def main() -> int:
    global OUT
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check", action="store_true",
        help="fail unless every generated module is already byte-for-byte current")
    parser.add_argument("--pilot", action="store_true",
                        help="the superseded earlier variant (region 0, P000--P015)")
    parser.add_argument("--out", type=Path, default=OUT,
                        help="OmegaBound directory to write/check (default: this checkout)")
    parser.add_argument("--axioms", action="store_true",
                        help="also emit the audit-only ReleaseCompactR61CohortsAxioms module")
    parser.add_argument("--leaves", type=Path,
                        help="require byte equality with the definition lines of these leaves")
    args = parser.parse_args()
    OUT = args.out.resolve()
    if args.pilot:
        sources, literals = pilot_sources(), None
    else:
        sources, literals = production_sources(OUT, args.axioms)
    if args.leaves is not None:
        if literals is None:
            raise SystemExit("--leaves applies to the production cohorts only")
        bad = leaf_mismatches(args.leaves, literals)
        for line in bad:
            print(f"leaf mismatch: {line}", file=sys.stderr)
        if bad:
            return 1
        print(f"all {len(literals)} coefficient definitions equal their leaves byte for byte")
    stale = []
    for path, source in sources.items():
        if args.check:
            if not path.is_file() or path.read_text() != source:
                stale.append(path)
        else:
            path.write_text(source)
            print(f"wrote {path} ({len(source.encode())} bytes)")
    if stale:
        for path in stale:
            print(f"stale generated module: {path}", file=sys.stderr)
        return 1
    if args.check:
        print(f"{len(sources)} Round-61 cohort modules are byte-for-byte current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
